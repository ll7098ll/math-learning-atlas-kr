def main():
    relations = read(ROOT, 'data/revised_relations.json')['relations']
    literature = read(ROOT, 'data/literature_claim_reviews.json')
    path = ROOT / FILE
    output = read(ROOT, FILE) if path.exists() else dict(schema_version=1, reviewer='Codex', date='2026-11-09', records=[])
    recorded = {(row['relation_id'], row['claim_id']): row for row in output['records']}
    by_relation = {r['id']: r for r in relations}
    claims = {c['id']: c for c in literature['claims']}
    rows = output['records']
    for reference, claim_id, role, finding, limit in REVIEWS:
        relation_id = 'REV-' + reference if reference[0].isdigit() else reference
        claim = claims[claim_id]
        pair = relation_id, claim_id
        if pair in recorded:
            assert all(recorded[pair][key] == value for key, value in dict(role=role, finding=finding, limit=limit).items()), pair
            continue
        rows.append(dict(relation_id=relation_id, claim_id=claim_id, role=role, finding=finding, limit=limit,
                         relation_snapshot=relation_snapshot(by_relation[relation_id]),
                         claim_snapshot=claim_snapshot(claim, literature['sources'][claim['source_id']])))
    apply_literature_context(relations, literature, registry=output)
    if len(rows) != len(recorded):
        path.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(len({row['relation_id'] for row in rows}), len(rows))


if __name__ == '__main__':
    main()
