ROOT = Path(__file__).resolve().parents[1]
ENTRIES, CASES = [], []
CODE = None
STANDARDS = {s['code']: s for s in json.loads((ROOT/'data/standards.json').read_text(encoding='utf-8'))['standards']}
REVIEW = dict(state='self_checked', reviewer='Codex', date=date.today().isoformat(), independent_review=False, student_validated=False)


def standard(code, scope, goals):
    global CODE
    CODE = code
    statement = STANDARDS[code]['statement_display']
    norm = lambda s: ''.join(s.split())
    for key, title, span, success in goals:
        assert norm(span) in norm(statement), (code, span)
    ENTRIES.append(dict(code=code, official_goal=statement, scope=scope,
                        goals=[dict(id=code+':'+key, title=title, official_span=span, success=success) for key,title,span,success in goals],
                        source_review=dict(kind='curriculum_text_and_application_notes', source_id='CURRICULUM_2022_33', pdf_pages=[17,18], printed_pages=[11,12],
                                           scope='공식 문장과 해설 및 적용 시 고려 사항의 텍스트 대조. 원문 이미지 대조 상태는 별도로 유지한다.'),
                        review=dict(REVIEW)))


def condition(text, kind='within_task', ref=None, reason=None):
    return dict(text=text, kind=kind, **({'goal_id':ref} if ref else {}), rationale=reason or text)


def route(key, title, conditions, steps, result, question, expected):
    return dict(id=key, title=title, operator='AND', conditions=[c['text'] for c in conditions],
                condition_sources=[dict(condition_index=i, **{k:v for k,v in c.items() if k!='text'}) for i,c in enumerate(conditions)],
                steps=steps, result=result, diagnostic=dict(question=question, expected=expected))


def case(key, title, goals, goal, task, shared, routes, note):
    CASES.append(dict(id='early-'+CODE+'-'+key, standard=CODE, title=title, goal_ids=[CODE+':'+g for g in goals],
                      goal=goal, task=task, shared_conditions=shared, routes=routes, route_relationship='alternative_explanations',
                      alternative_review=note, notes=note, review=dict(REVIEW)))


