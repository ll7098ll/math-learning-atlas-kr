def write():
    all_goals = {g['id'] for entry in ENTRIES for g in entry['goals']}
    for entry in ENTRIES:
        for goal in entry['goals']:
            goal['case_ids'] = [c['id'] for c in CASES if goal['id'] in c['goal_ids']]
            assert goal['case_ids'], goal['id']
    for c in CASES:
        assert set(c['goal_ids']) <= all_goals
        for r in c['routes']:
            assert len(r['conditions']) == len(r['condition_sources'])
            for source in r['condition_sources']:
                assert source['kind'] in ('goal','entry_capability','within_task','task_assumption')
                if source['kind']=='goal': assert source['goal_id'] in all_goals
    assert len(ENTRIES)==11 and {e['code'] for e in ENTRIES}=={c for c in STANDARDS if c.startswith('2수01-')}
    destination = ROOT/'data/goal_hierarchy_early_number.json'
    previous = json.loads(destination.read_text(encoding='utf-8')) if destination.exists() else {}
    for key, records, id_key in [('entries',ENTRIES,'code'), ('cases',CASES,'id')]:
        old = {r[id_key]:r for r in previous.get(key,[])}
        for record in records:
            prior = old.get(record[id_key])
            body = lambda r: {k:v for k,v in r.items() if k not in ('review','history')}
            changed = prior is not None and body(prior)!=body(record)
            if prior and not changed:
                record['review'] = prior['review']
            if changed:
                assert not prior['review'].get('independent_review') and not prior['review'].get('student_validated'), 'Reconcile external review before changing '+record[id_key]
            record['history'] = list(prior.get('history',[])) if prior else []
            if not record['history'] or changed:
                record['history'].append(dict(date=date.today().isoformat(),reviewer='Codex',kind='self_check',scope=record.get('scope',record.get('task')),method='공식 문구·해설 범위, 예시 계산, 반례, 조건 출처 및 대안 경로 대조',**({'previous_record':body(prior)} if changed else {})))
    source_pdf = ROOT/'[별책8] 수학과 교육과정.pdf'
    result = dict(schema_version=1, source_pdf_sha256=hashlib.sha256(source_pdf.read_bytes()).hexdigest(),
                  analysis_scope='1~2학년군 수와 연산 11개 기준의 목표 분해와 대표 과제별 조건. 모든 수·상황의 숙달이나 발달 순서를 검증했다는 뜻은 아니다.',
                  entries=ENTRIES, cases=CASES)
    destination.write_text(json.dumps(result,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    registry_file=ROOT/'data/hierarchy_review_registry.json'
    registry=json.loads(registry_file.read_text(encoding='utf-8'))
    for entry in ENTRIES:
        record=registry['standards'][entry['code']]
        if record['state']=='unreviewed':record['state']='in_progress'
        inventory=dict(source='data/'+destination.name,goal_ids=[g['id'] for g in entry['goals']],
                       review_state=entry['review']['state'],scope=entry['scope'])
        if record.get('goal_analysis')!=inventory:
            record.setdefault('history',[]).append(dict(date=date.today().isoformat(),reviewer='Codex',kind='goal_decomposition',scope=entry['scope'],source=inventory['source']))
            record['goal_analysis']=inventory
    registry_file.write_text(json.dumps(registry,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'Authored {len(ENTRIES)} standards, {len(all_goals)} constituent goals, {len(CASES)} cases')


if __name__=='__main__': write()
