def case(code,title,goal,task,shared,routes,notes=''):
    CASES.append({'id':'task-'+code,'standard':code,'title':title,'goal':goal,'task':task,
                  'shared_conditions':shared,'routes':routes,'route_relationship':'alternative_explanations',
                  'notes':notes,'review':{'state':'self_checked','reviewer':'Codex','date':'2026-10-30','independent_review':False,'student_validated':False}})


def route(id,title,conditions,steps,result,question,expected):
    return dict(id=id,title=title,operator='AND',conditions=conditions,steps=steps,result=result,
                diagnostic={'question':question,'expected':expected})


